  static String tr(String key) {
    final lang = languageNotifier.value;
    return _t[key]?[lang] ?? key;
  }

  // ── Theme helpers ──────────────────────────────────────────────────────────
  static bool get isDark {
    final mode = themeModeNotifier.value;
    if (mode == 'dark') return true;
    if (mode == 'light') return false;
    final brightness = WidgetsBinding.instance.platformDispatcher.platformBrightness;
    return brightness == Brightness.dark;
  }

  static LinearGradient get currentGradient =>
      isDark ? appGradient : lightGradient;

  static Color get currentCardBg =>
      isDark ? cardBg : const Color(0xFFFFFFFF);

  static Color get currentTextColor =>
      isDark ? Colors.white : const Color(0xFF1A2332);

  static Color get currentSubTextColor =>
      isDark ? Colors.white : const Color(0xFF1A2332);

  // ── Reusable Widgets ───────────────────────────────────────────────────────
  static Widget backButton(BuildContext context) => Padding(
    padding: const EdgeInsets.all(10),
    child: ClipOval(
      child: Container(
        decoration: BoxDecoration(
          color: Colors.white.withValues(alpha: 0.1),
          shape: BoxShape.circle,
          border: Border.all(color: Colors.white.withValues(alpha: 0.2)),
        ),
        child: IconButton(
          icon: const Icon(Icons.arrow_back_ios_new_rounded, size: 16),
          onPressed: () => Navigator.pop(context),
          color: Colors.white,
        ),
      ),
    ),
  );

  static Widget blob(double size, Color color) => Container(
    width: size,
    height: size,
    decoration: BoxDecoration(shape: BoxShape.circle, color: color),
  );

  static void toast(BuildContext context, String msg, Color color) {
    if (!Navigator.of(context).mounted) return;
    ScaffoldMessenger.of(context).showSnackBar(SnackBar(
      content: Row(children: [
        const Icon(Icons.info_outline_rounded, color: Colors.white, size: 18),
        const SizedBox(width: 10),
        Expanded(
          child: Text(msg,
              style: const TextStyle(
                  fontSize: 13, fontWeight: FontWeight.w500)),
        ),
      ]),
      backgroundColor: color,
      behavior: SnackBarBehavior.floating,
      shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(14)),
      margin: const EdgeInsets.all(16),
      duration: const Duration(seconds: 4),
    ));
  }

  static Widget sectionHeader(String title, IconData icon, Color color) =>
      Padding(
        padding: const EdgeInsets.only(bottom: 10, left: 4),
        child: Row(children: [
          Container(
            padding: const EdgeInsets.all(6),
            decoration: BoxDecoration(
