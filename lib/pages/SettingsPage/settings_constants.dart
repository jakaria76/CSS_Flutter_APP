                  ],
                ),
              ),
              trailing ??
                  Icon(Icons.arrow_forward_ios_rounded,
                      size: 14,
                      color: Colors.white.withValues(alpha: isDark ? 0.25 : 0.4)),
            ]),
          ),
        ),
      );
